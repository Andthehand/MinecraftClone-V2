constexpr int Hex(char value) { return value <= '9' ? value - '0' : value - 'A' + 10; }

inline std::array<uint8_t, WIDTH * HEIGHT * 4> BuildAtlas() {
    std::array<uint8_t, WIDTH * HEIGHT * 4> pixels{};

    for (int glyph = 0; glyph < int(ROWS.size()); ++glyph) {
        for (int y = 0; y < GLYPH_HEIGHT; ++y) {
            const int row = Hex(ROWS[glyph][y * 2]) * 16 + Hex(ROWS[glyph][y * 2 + 1]);

            for (int x = 0; x < GLYPH_WIDTH; ++x) {
                const int index = ((glyph / 16 * 8 + y) * WIDTH + glyph % 16 * 8 + x) * 4;
                pixels[index] = pixels[index + 1] = pixels[index + 2] = 255;
                pixels[index + 3] = (row & (1 << (4 - x))) ? 255 : 0;
            }
        }
    }

    return pixels;
}
